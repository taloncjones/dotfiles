spec = importlib.util.spec_from_file_location("adapter", "codex/hooks/orch_edit_guard.py")
adapter = importlib.util.module_from_spec(spec)
spec.loader.exec_module(adapter)
thread = "11111111-1111-1111-1111-111111111111"
shell = adapter.normalize({"tool_name": "exec_command", "thread_id": thread,
                           "tool_input": {"cmd": "echo x > tracked.txt", "workdir": "/repo"}})
assert shell["tool_name"] == "Bash" and shell["session_id"] == thread
assert shell["cwd"] == "/repo" and shell["tool_input"]["command"] == "echo x > tracked.txt"
shell_args = adapter.normalize({"tool_name": "unified_exec", "thread_id": thread,
                                "tool_input": {"args": {"cmd": "echo x > tracked.txt", "workdir": "/nested"}}})
assert shell_args["cwd"] == "/nested"
patch = adapter.normalize({"tool_name": "apply_patch", "thread_id": thread,
                           "tool_input": {"input": "*** Update File: [id].txt\n*** Move to: $name.txt\n"}})
assert patch["tool_name"] == "Write" and patch["tool_input"]["file_paths"] == ["[id].txt", "$name.txt"]
PY
then
    printf 'PASS  Codex adapter normalizes exec_command and apply_patch payloads\n'
    PASS=$((PASS + 1))
else
    printf 'FAIL  Codex adapter normalizes exec_command and apply_patch payloads\n' >&2
    FAIL=$((FAIL + 1))
fi

