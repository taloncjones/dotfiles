#!/bin/sh
# herdr-manifest.test.sh -- tests for install/common/herdr_manifest.py, which
# writes herdr's Claude detection override (remote manifest + one shell rule).
# Cases 19-25 ask the real herdr to classify the fixture screens and print
# SKIP when herdr or its remote cache is missing.
set -u

GEN=install/common/herdr_manifest.py
FRAGMENT=herdr/agent-detection/claude-rules.toml
FIXTURES=herdr/agent-detection/fixtures
[ -f "$GEN" ] || { echo "FAIL: $GEN not found (run from repo root)" >&2; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: python3 required"; exit 0; }

PASS=0; FAIL=0
pass() { printf 'PASS  %s\n' "$1"; PASS=$((PASS + 1)); }
fail() { printf 'FAIL  %s\n' "$1" >&2; FAIL=$((FAIL + 1)); }
skip() { printf 'SKIP  %s\n' "$1"; }

TMP="$(mktemp -d "${TMPDIR:-/tmp}/herdr-manifest-test.XXXXXX")"
TMP="$(cd "$TMP" && pwd)"
[ -n "${KEEP_TMP:-}" ] || trap 'rm -rf "$TMP"' EXIT

REPO="$(pwd)"
REAL_HERDR="$(command -v herdr 2>/dev/null || true)"
REAL_CACHE="${XDG_STATE_HOME:-$HOME/.local/state}/herdr/agent-detection/remote/claude.toml"

# Stub herdr: logs argv, exits $STUB_RC (default 0).
STUB_BIN="$TMP/stub-bin"
mkdir -p "$STUB_BIN"
cat >"$STUB_BIN/herdr" <<'STUB'
#!/bin/sh
printf '%s\n' "$*" >>"$STUB_LOG"
exit "${STUB_RC:-0}"
STUB
chmod +x "$STUB_BIN/herdr"
# PATH without herdr for case 16 (python3 and coreutils only).
NOHERDR_BIN="$TMP/noherdr-bin"
mkdir -p "$NOHERDR_BIN"
for tool in python3 mktemp; do ln -s "$(command -v $tool)" "$NOHERDR_BIN/$tool"; done

# Spec objects: one source of truth for expected values.
REMOTE_V1='id = "claude"
version = "2026.01.01.1"

[[rules]]
id = "remote_rule"
state = "idle"
priority = 1
region = "whole_recent"
contains = ["x"]
'
REMOTE_V2="$(printf '%s' "$REMOTE_V1" | sed 's/2026.01.01.1/2026.02.02.2/')"
MARKER='# dotfiles-generated by install/common/herdr_manifest.py; do not edit'

# Per-case dirs: cfg/ and st/ under $TMP/<name>; override and cache paths follow.
# run_gen <name> [PATH] [generator] [stub exit code] runs the generator with
# the stub herdr first on PATH. Arguments, not env prefixes: a prefix on a
# shell function call can persist in sh.
run_gen() {
    env XDG_CONFIG_HOME="$TMP/$1/cfg" XDG_STATE_HOME="$TMP/$1/st" \
        PATH="${2:-$STUB_BIN:$PATH}" STUB_LOG="$TMP/$1/stub.log" STUB_RC="${4:-0}" \
        python3 "${3:-$GEN}" >"$TMP/$1/out.log" 2>&1
}
new_case() {
    mkdir -p "$TMP/$1/st/herdr/agent-detection/remote"
    : >"$TMP/$1/stub.log"
}
reload_count() { grep -c '^server reload-agent-manifests$' "$TMP/$1/stub.log"; }
sha() { python3 -c 'import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest())' "$1"; }

# --- 1-3, 5: first write
new_case c1
printf '%s' "$REMOTE_V1" >"$TMP/c1/st/herdr/agent-detection/remote/claude.toml"
OV1="$TMP/c1/cfg/herdr/agent-detection/claude.toml"
run_gen c1; rc=$?
{
    printf '%s\n' "$MARKER"
    printf '# source: herdr remote claude.toml version 2026.01.01.1, sha256 %s\n' "$(sha "$TMP/c1/st/herdr/agent-detection/remote/claude.toml")"
    printf '# rules: herdr/agent-detection/claude-rules.toml\n'
    printf '%s' "$REMOTE_V1"
    printf '\n'
    cat "$FRAGMENT"
} >"$TMP/c1/expected.toml"
if [ "$rc" -eq 0 ] && cmp -s "$OV1" "$TMP/c1/expected.toml"; then
    pass "1 writes header + remote + blank line + fragment"
else
    fail "1 writes header + remote + blank line + fragment"
fi
if [ "$(sed -n 1p "$OV1")" = "$MARKER" ] &&
   sed -n 2p "$OV1" | grep -qF "version 2026.01.01.1, sha256 $(sha "$TMP/c1/st/herdr/agent-detection/remote/claude.toml")"; then
    pass "2 header names the marker, remote version and sha256"
else
    fail "2 header names the marker, remote version and sha256"
fi
if python3 - "$OV1" <<'PY'
import sys, tomllib
d = tomllib.load(open(sys.argv[1], "rb"))
ids = [r["id"] for r in d["rules"]]
sys.exit(0 if d["id"] == "claude" and ids.count("dotfiles_background_shells_working") == 1 and "remote_rule" in ids else 1)
PY
then pass "3 override parses with id claude and the dotfiles rule once"
else fail "3 override parses with id claude and the dotfiles rule once"; fi
[ "$(reload_count c1)" = "1" ] && pass "5 first write logs one reload" || fail "5 first write logs one reload"

# --- 4: fragment holds exactly the specified rule
if python3 - "$FRAGMENT" <<'PY'
import sys, tomllib
want = [{
    "id": "dotfiles_background_shells_working",
    "state": "working",
    "priority": 960,
    "region": "after_last_horizontal_rule",
    "visible_working": True,
    "line_regex": ['(?:^|\\s·)\\s+[1-9]\\d*\\s+shells?(?:\\s+·|,|\\s*$)'],
    "not": [{"contains": [s]} for s in (
        "do you want to proceed?", "esc to cancel", "waiting for permission",
        "do you want to allow this connection?", "tab to amend", "ctrl+e to explain")],
}]
d = tomllib.load(open(sys.argv[1], "rb"))
sys.exit(0 if d == {"rules": want} else 1)
PY
then pass "4 fragment rules equal the specified rule in full"
else fail "4 fragment rules equal the specified rule in full"; fi

# --- 6: unchanged rerun
touch -t 202001010000 "$OV1"
before="$(cksum <"$OV1")"; mt1="$(ls -l "$OV1")"
run_gen c1; rc=$?
if [ "$rc" -eq 0 ] && [ "$(cksum <"$OV1")" = "$before" ] && [ "$(ls -l "$OV1")" = "$mt1" ] && [ "$(reload_count c1)" = "2" ]; then
    pass "6 unchanged rerun keeps bytes and mtime and reloads again"
else
    fail "6 unchanged rerun keeps bytes and mtime and reloads again"
fi

# --- 7: changed remote regenerates
printf '%s' "$REMOTE_V2" >"$TMP/c1/st/herdr/agent-detection/remote/claude.toml"
run_gen c1; rc=$?
if [ "$rc" -eq 0 ] && sed -n 2p "$OV1" | grep -qF "version 2026.02.02.2, sha256 $(sha "$TMP/c1/st/herdr/agent-detection/remote/claude.toml")"; then
    pass "7 changed remote regenerates the override with the new sha256"
else
    fail "7 changed remote regenerates the override with the new sha256"
fi

# --- 8: nothing to do
new_case c8
rmdir "$TMP/c8/st/herdr/agent-detection/remote"
run_gen c8; rc=$?
if [ "$rc" -eq 0 ] && [ ! -e "$TMP/c8/cfg" ] && [ "$(reload_count c8)" = "0" ]; then
    pass "8 no cache and no override creates nothing and skips reload"
else
    fail "8 no cache and no override creates nothing and skips reload"
fi

# --- 9: cache gone, generated override stays and reloads
new_case c9
mkdir -p "$TMP/c9/cfg/herdr/agent-detection"
cp "$OV1" "$TMP/c9/cfg/herdr/agent-detection/claude.toml"
cp "$OV1" "$TMP/c9/before.toml"
run_gen c9; rc=$?
if [ "$rc" -eq 0 ] && cmp -s "$TMP/c9/before.toml" "$TMP/c9/cfg/herdr/agent-detection/claude.toml" && [ "$(reload_count c9)" = "1" ]; then
    pass "9 no cache keeps a generated override and reloads once"
else
    fail "9 no cache keeps a generated override and reloads once"
fi

# --- 10: user-authored override
new_case c10
printf '%s' "$REMOTE_V1" >"$TMP/c10/st/herdr/agent-detection/remote/claude.toml"
mkdir -p "$TMP/c10/cfg/herdr/agent-detection"
printf 'id = "claude"\nversion = "hand"\n' >"$TMP/c10/cfg/herdr/agent-detection/claude.toml"
cp "$TMP/c10/cfg/herdr/agent-detection/claude.toml" "$TMP/c10/before.toml"
run_gen c10; rc=$?
if [ "$rc" -eq 0 ] && cmp -s "$TMP/c10/before.toml" "$TMP/c10/cfg/herdr/agent-detection/claude.toml" &&
   [ "$(reload_count c10)" = "0" ] && grep -q '^\[WARNING\]' "$TMP/c10/out.log"; then
    pass "10 user-authored override stays untouched with no reload"
else
    fail "10 user-authored override stays untouched with no reload"
fi

# --- 11-14: errors keep the prior override
new_err_case() {
    new_case "$1"
    mkdir -p "$TMP/$1/cfg/herdr/agent-detection"
    cp "$OV1" "$TMP/$1/cfg/herdr/agent-detection/claude.toml"
    cp "$OV1" "$TMP/$1/before.toml"
}
err_case_ok() {
    [ "$2" -eq 1 ] && cmp -s "$TMP/$1/before.toml" "$TMP/$1/cfg/herdr/agent-detection/claude.toml" &&
        grep -q '^\[X\]' "$TMP/$1/out.log" && [ "$(reload_count "$1")" = "0" ] &&
        [ -z "$(ls -A "$TMP/$1/cfg/herdr/agent-detection" | grep '^\.claude\..*\.tmp$')" ]
}
new_err_case c11
printf 'broken = [\n' >"$TMP/c11/st/herdr/agent-detection/remote/claude.toml"
run_gen c11; rc=$?
err_case_ok c11 "$rc" && pass "11 invalid remote TOML exits 1 and keeps the override" || fail "11 invalid remote TOML exits 1 and keeps the override"

new_err_case c12
printf 'id = "codex"\nversion = "1"\n' >"$TMP/c12/st/herdr/agent-detection/remote/claude.toml"
run_gen c12; rc=$?
err_case_ok c12 "$rc" && pass "12 remote with another id exits 1 and keeps the override" || fail "12 remote with another id exits 1 and keeps the override"

new_err_case c13
mkdir -p "$TMP/c13/tree/install/common"
cp "$GEN" "$TMP/c13/tree/install/common/herdr_manifest.py"
printf '%s' "$REMOTE_V1" >"$TMP/c13/st/herdr/agent-detection/remote/claude.toml"
run_gen c13 "$STUB_BIN:$PATH" "$TMP/c13/tree/install/common/herdr_manifest.py"; rc=$?
err_case_ok c13 "$rc" && pass "13 missing fragment exits 1 and keeps the override" || fail "13 missing fragment exits 1 and keeps the override"

new_err_case c14
{ printf '%s\n' "$REMOTE_V1"; cat "$FRAGMENT"; } >"$TMP/c14/st/herdr/agent-detection/remote/claude.toml"
run_gen c14; rc=$?
err_case_ok c14 "$rc" && pass "14 remote already holding the dotfiles rule exits 1" || fail "14 remote already holding the dotfiles rule exits 1"

# --- 15: failing reload
new_case c15
printf '%s' "$REMOTE_V1" >"$TMP/c15/st/herdr/agent-detection/remote/claude.toml"
run_gen c15 "$STUB_BIN:$PATH" "$GEN" 1; rc=$?
if [ "$rc" -eq 0 ] && [ -f "$TMP/c15/cfg/herdr/agent-detection/claude.toml" ] && [ "$(grep -c '^\[INFO\]' "$TMP/c15/out.log")" = "1" ]; then
    pass "15 failing reload still writes, exits 0 and prints one INFO line"
else
    fail "15 failing reload still writes, exits 0 and prints one INFO line"
fi

# --- 16: no herdr on PATH
new_case c16
printf '%s' "$REMOTE_V1" >"$TMP/c16/st/herdr/agent-detection/remote/claude.toml"
run_gen c16 "$NOHERDR_BIN"; rc=$?
if [ "$rc" -eq 0 ] && [ -f "$TMP/c16/cfg/herdr/agent-detection/claude.toml" ] && [ ! -s "$TMP/c16/stub.log" ]; then
    pass "16 no herdr on PATH writes without attempting a reload"
else
    fail "16 no herdr on PATH writes without attempting a reload"
fi

# --- 17: no temp file left
if [ -z "$(ls -A "$TMP/c1/cfg/herdr/agent-detection" | grep '^\.claude\..*\.tmp$')" ]; then
    pass "17 successful runs leave no temp file"
else
    fail "17 successful runs leave no temp file"
fi

# --- 18: a waiting run publishes the fragment current at lock time
new_case c18
mkdir -p "$TMP/c18/tree/install/common" "$TMP/c18/tree/herdr/agent-detection" "$TMP/c18/cfg/herdr/agent-detection"
cp "$GEN" "$TMP/c18/tree/install/common/herdr_manifest.py"
cp "$FRAGMENT" "$TMP/c18/tree/herdr/agent-detection/claude-rules.toml"
printf '%s' "$REMOTE_V1" >"$TMP/c18/st/herdr/agent-detection/remote/claude.toml"
python3 - "$TMP/c18/cfg/herdr/agent-detection" "$TMP/c18/held" <<'PY' &
import fcntl, os, sys, time
fd = os.open(sys.argv[1], os.O_RDONLY)
fcntl.flock(fd, fcntl.LOCK_EX)
open(sys.argv[2], "w").close()
time.sleep(2)
PY
HOLDER=$!
n=0; while [ ! -e "$TMP/c18/held" ] && [ "$n" -lt 100 ]; do sleep 0.1; n=$((n + 1)); done
run_gen c18 "$STUB_BIN:$PATH" "$TMP/c18/tree/install/common/herdr_manifest.py" &
RUNNER=$!
sleep 0.5
printf '\n# fragment rewritten while locked\n' >>"$TMP/c18/tree/herdr/agent-detection/claude-rules.toml"
wait "$RUNNER"; rc=$?
wait "$HOLDER"
if [ "$rc" -eq 0 ] && grep -q 'fragment rewritten while locked' "$TMP/c18/cfg/herdr/agent-detection/claude.toml"; then
    pass "18 a run that waited on the lock publishes the rewritten fragment"
else
    fail "18 a run that waited on the lock publishes the rewritten fragment"
fi

# --- 19-25: real herdr classifies the fixture screens
if [ -n "$REAL_HERDR" ] && [ -f "$REAL_CACHE" ]; then
    LIVE_OK=1
    mkdir -p "$TMP/live/st/herdr/agent-detection/remote"
    cp "$REAL_CACHE" "$TMP/live/st/herdr/agent-detection/remote/claude.toml"
    : >"$TMP/live/stub.log"
    run_gen live || LIVE_OK=0
else
    LIVE_OK=skip
fi
# explain <fixture> -> "<state> <rule id>"
explain() {
    XDG_STATE_HOME="$TMP/live/st" XDG_CONFIG_HOME="$TMP/live/cfg" \
        "$REAL_HERDR" agent explain --file "$FIXTURES/$1" --agent claude --json 2>/dev/null |
        python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("state"), (d.get("matched_rule") or {}).get("id"))'
}
for spec in \
    "19 idle-one-shell.txt working dotfiles_background_shells_working" \
    "20 idle-two-shells.txt working dotfiles_background_shells_working" \
    "21 idle-shells-only.txt working dotfiles_background_shells_working" \
    "26 idle-shell-monitors.txt working dotfiles_background_shells_working" \
    "22 idle-no-shell.txt idle" \
    "23 shell-exited.txt idle" \
    "24 quoted-footer.txt idle" \
    "25 permission-with-shell.txt blocked"
do
    set -- $spec
    num=$1; fx=$2; want_state=$3; want_rule="${4:-}"
    if [ "$LIVE_OK" = "skip" ]; then
        skip "$num live: $fx (no herdr or remote cache)"
        continue
    fi
    got="$([ "$LIVE_OK" = 1 ] && explain "$fx")"
    if [ "${got%% *}" = "$want_state" ] && { [ -z "$want_rule" ] || [ "${got#* }" = "$want_rule" ]; }; then
        pass "$num live: $fx reads $want_state"
    else
        fail "$num live: $fx reads $want_state (got: $got)"
    fi
done

printf '%d passed, %d failed\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
