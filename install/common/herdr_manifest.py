#!/usr/bin/env python3
"""Write herdr's Claude detection override: cached remote manifest plus one rule."""

import fcntl
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import time

MARKER = "# dotfiles-generated by install/common/herdr_manifest.py; do not edit"
RULE_ID = "dotfiles_background_shells_working"
LOCK_WAIT_SECS = 30
RELOAD = ["herdr", "server", "reload-agent-manifests"]
FRAGMENT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "herdr",
    "agent-detection",
    "claude-rules.toml",
)


def reload_herdr():
    if shutil.which("herdr") is None:
        print("[INFO] herdr not on PATH; run: herdr server reload-agent-manifests")
        return
    try:
        done = subprocess.run(RELOAD, capture_output=True, timeout=10)
        ok = done.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        ok = False
    if not ok:
        print("[INFO] herdr reload failed; run: herdr server reload-agent-manifests")


def lock_dir(fd):
    deadline = time.monotonic() + LOCK_WAIT_SECS
    while True:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            return True
        except OSError:
            if time.monotonic() >= deadline:
                return False
            time.sleep(0.1)


def read_bytes(path):
    try:
        with open(path, "rb") as f:
            return f.read()
    except FileNotFoundError:
        return None


def compose(tomllib, remote, fragment):
    """Return (output bytes, error message)."""
    try:
        remote_doc = tomllib.loads(remote.decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        return None, f"remote claude.toml is not valid TOML: {exc}"
    if remote_doc.get("id") != "claude":
        return None, "remote claude.toml top-level id is not claude"
    if any(r.get("id") == RULE_ID for r in remote_doc.get("rules", [])):
        return None, f"remote claude.toml already has rule {RULE_ID}"
    try:
        tomllib.loads(fragment.decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        return None, f"rules fragment is not valid TOML: {exc}"
    header = (
        f"{MARKER}\n"
        f"# source: herdr remote claude.toml version {remote_doc.get('version', 'unknown')}, "
        f"sha256 {hashlib.sha256(remote).hexdigest()}\n"
        "# rules: herdr/agent-detection/claude-rules.toml\n"
    )
    body = remote if remote.endswith(b"\n") else remote + b"\n"
    out = header.encode() + body + b"\n" + fragment
    try:
        rules = tomllib.loads(out.decode("utf-8")).get("rules", [])
    except tomllib.TOMLDecodeError as exc:
        return None, f"composed override is not valid TOML: {exc}"
    if [r.get("id") for r in rules].count(RULE_ID) != 1:
        return None, f"composed override does not hold {RULE_ID} exactly once"
    return out, None


def publish(target_dir, target, data):
    fd, tmp = tempfile.mkstemp(prefix=".claude.", suffix=".tmp", dir=target_dir)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, target)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    dfd = os.open(target_dir, os.O_RDONLY)
    try:
        os.fsync(dfd)
    finally:
        os.close(dfd)


def run(tomllib):
    home = os.path.expanduser("~")
    config = os.environ.get("XDG_CONFIG_HOME") or os.path.join(home, ".config")
    state = os.environ.get("XDG_STATE_HOME") or os.path.join(home, ".local", "state")
    target_dir = os.path.join(config, "herdr", "agent-detection")
    target = os.path.join(target_dir, "claude.toml")
    remote_path = os.path.join(
        state, "herdr", "agent-detection", "remote", "claude.toml"
    )

    if not os.path.exists(remote_path) and not os.path.exists(target):
        print("[INFO] no herdr remote claude.toml cache and no override; skipping")
        return 0, False

    os.makedirs(target_dir, exist_ok=True)
    dir_fd = os.open(target_dir, os.O_RDONLY)
    try:
        if not lock_dir(dir_fd):
            print("[X] another herdr_manifest.py run holds the lock")
            return 1, False
        existing = read_bytes(target)
        if existing is not None and existing.split(b"\n", 1)[0] != MARKER.encode():
            print(
                f"[WARNING] {target} is user-authored (first line is not the marker); leaving it"
            )
            return 0, False
        generated = existing is not None
        remote = read_bytes(remote_path)
        if remote is None:
            print(
                "[INFO] no herdr remote claude.toml cache; leaving the existing override"
            )
            return 0, generated
        fragment = read_bytes(FRAGMENT)
        if fragment is None:
            print(f"[X] missing rules fragment {FRAGMENT}")
            return 1, False
        out, err = compose(tomllib, remote, fragment)
        if err:
            print(f"[X] {err}")
            return 1, False
        if out != existing:
            publish(target_dir, target, out)
            print(f"[OK] wrote {target}")
        return 0, True
    finally:
        os.close(dir_fd)


def main():
    try:
        import tomllib
    except ImportError:
        print("[WARNING] python tomllib unavailable; herdr override not generated")
        return 0
    status, reload = run(tomllib)
    if reload:
        reload_herdr()
    return status


if __name__ == "__main__":
    sys.exit(main())
